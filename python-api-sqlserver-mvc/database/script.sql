CREATE DATABASE AtlanticoTuristico;
GO
USE AtlanticoTuristico;
GO
CREATE TABLE dbo.Municipios(id INT IDENTITY PRIMARY KEY,nombre NVARCHAR(150) UNIQUE NOT NULL,subregion NVARCHAR(150));
CREATE TABLE dbo.Tipos(id INT IDENTITY PRIMARY KEY,nombre NVARCHAR(150) UNIQUE NOT NULL);
CREATE TABLE dbo.Atractivos(id INT IDENTITY PRIMARY KEY,id_api NVARCHAR(100) UNIQUE NULL,municipio_id INT NULL,tipo_id INT NULL,nombre NVARCHAR(300) NOT NULL,ubicacion NVARCHAR(300),descripcion NVARCHAR(MAX),origen NVARCHAR(20) DEFAULT 'LOCAL',fecha_importacion DATETIME2,FOREIGN KEY(municipio_id) REFERENCES dbo.Municipios(id),FOREIGN KEY(tipo_id) REFERENCES dbo.Tipos(id));
CREATE TABLE dbo.Resenas(id INT IDENTITY PRIMARY KEY,atractivo_id INT NOT NULL,calificacion TINYINT NOT NULL CHECK(calificacion BETWEEN 1 AND 5),comentario NVARCHAR(1000) NOT NULL,fecha DATETIME2 DEFAULT SYSDATETIME(),FOREIGN KEY(atractivo_id) REFERENCES dbo.Atractivos(id) ON DELETE CASCADE);
GO
